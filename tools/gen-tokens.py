NS = ('xmlns="https://github.com/avaloniaui"\n'
      '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"')


def palette_keys():
    return {k for k, _, _ in PALETTE}


def color_value(v):
    if v.startswith("#"):
        return v
    raise ValueError(v)


def color_ref(v):
    if isinstance(v, tuple):
        return color_ref(v[0])
    if v.startswith("#"):
        return v
    if v not in palette_keys():
        raise ValueError(f"unknown palette key {v}")
    return "{DynamicResource %s}" % v


def brush_xaml(key, value, indent):
    pad = " " * indent
    if isinstance(value, str):
        if value.startswith("#"):
            return f'{pad}<SolidColorBrush x:Key="{key}" Color="{value}" />'
        return f'{pad}<SolidColorBrush x:Key="{key}" Color="{color_ref(value)}" />'
    if value[0] == "linear":
        _, direction, stops = value
        end = "0%,100%" if direction == V else "100%,0%"
        lines = [f'{pad}<LinearGradientBrush x:Key="{key}" StartPoint="0%,0%" EndPoint="{end}">']
        for offset, color in stops:
            lines.append(f'{pad}  <GradientStop Offset="{offset:g}" Color="{color_ref(color)}" />')
        lines.append(f"{pad}</LinearGradientBrush>")
        return "\n".join(lines)
    color, opacity = value
    return f'{pad}<SolidColorBrush x:Key="{key}" Color="{color_ref(color)}" Opacity="{opacity:g}" />'


def metric_xaml(key, kind, value, indent):
    pad = " " * indent
    if kind == D:
        return f'{pad}<x:Double x:Key="{key}">{value:g}</x:Double>'
    return f'{pad}<{kind} x:Key="{key}">{value}</{kind}>'


def type_metrics():
    rows = []
    for name, size, _weight, compact, line in TYPE_RAMP:
        rows.append((f"EnyoText{name}FontSize", D, size, compact))
        if line:
            rows.append((f"EnyoText{name}LineHeight", D, round(size * line, 2), round(compact * line, 2)))
    return rows


def all_metrics():
    return METRICS + type_metrics()


def gen_palette():
    out = [HEADER, f"<ResourceDictionary {NS}>", "  <ResourceDictionary.ThemeDictionaries>"]
    for variant, idx in (("Default", 1), ("Dark", 2)):
        out.append(f'    <ResourceDictionary x:Key="{variant}">')
        for row in PALETTE:
            out.append(f'      <Color x:Key="{row[0]}">{color_value(row[idx])}</Color>')
        out.append("    </ResourceDictionary>")
    out.append("  </ResourceDictionary.ThemeDictionaries>")
    out.append("</ResourceDictionary>")
    return "\n".join(out) + "\n"


def gen_base():
    out = [HEADER, f"<ResourceDictionary {NS}>", "  <ResourceDictionary.ThemeDictionaries>"]
    for variant, idx in (("Default", 1), ("Dark", 2)):
        out.append(f'    <ResourceDictionary x:Key="{variant}">')
        for section, rows in BRUSHES:
            out.append(f"      <!-- {section} -->")
            for row in rows:
                out.append(brush_xaml(row[0], row[idx], 6))
        out.append("      <!-- Shadows -->")
        for row in SHADOWS:
            out.append(f'      <BoxShadows x:Key="{row[0]}">{row[idx]}</BoxShadows>')
        out.append("    </ResourceDictionary>")
    out.append("  </ResourceDictionary.ThemeDictionaries>")
    out.append("")
    out.append("  <!-- Fonts -->")
    for key, value in FONTS:
        out.append(f'  <FontFamily x:Key="{key}">{value}</FontFamily>')
    out.append("")
    out.append("  <!-- Type ramp weights -->")
    for name, _size, weight, _compact, _line in TYPE_RAMP:
        out.append(f'  <FontWeight x:Key="EnyoText{name}FontWeight">{weight}</FontWeight>')
    out.append("")
    out.append("  <!-- Metrics (Default density; CompactMetrics.axaml overlays them) -->")
    for key, kind, value, _compact in all_metrics():
        out.append(metric_xaml(key, kind, value, 2))
    out.append("")
    out.append("  <!-- Motion, milliseconds -->")
    for key, ms in MOTION:
        out.append(f'  <x:Double x:Key="{key}">{ms}</x:Double>')
    out.append("</ResourceDictionary>")
    return "\n".join(out) + "\n"


def gen_compact():
    out = [HEADER, f"<ResourceDictionary {NS}>"]
    for key, kind, value, compact in all_metrics():
        out.append(metric_xaml(key, kind, value if compact is None else compact, 2))
    out.append("</ResourceDictionary>")
    return "\n".join(out) + "\n"


def layer2_keys():
    keys = []
    for _section, rows in BRUSHES:
        keys.extend(r[0] for r in rows)
    keys.extend(r[0] for r in SHADOWS)
    keys.extend(k for k, _ in FONTS)
    keys.extend(f"EnyoText{r[0]}FontWeight" for r in TYPE_RAMP)
    keys.extend(r[0] for r in all_metrics())
    keys.extend(k for k, _ in MOTION)
    return keys


def gen_tests():
    keys = layer2_keys()
    metrics = [r[0] for r in all_metrics()]
    lines = [
        "// <auto-generated>Generated by tools/gen-tokens.py. Do not edit; change the generator and rerun it.</auto-generated>",
        "namespace AvaEnyo.Theme.Tests;",
        "",
        "/// <summary>Every Layer 2 key and every palette key, generated with the tokens.</summary>",
        "public static class TokenKeys",
        "{",
        "    public static readonly string[] Layer2 =",
        "    [",
    ]
    lines.extend(f'        "{k}",' for k in keys)
    lines += ["    ];", "", "    public static readonly string[] Palette =", "    ["]
    lines.extend(f'        "{k}",' for k, _, _ in PALETTE)
    lines += ["    ];", "", "    public static readonly string[] Metrics =", "    ["]
    lines.extend(f'        "{k}",' for k in metrics)
    lines += ["    ];", "}"]
    return "\n".join(lines) + "\n"


def validate():
    seen = set()
    for k in layer2_keys() + [k for k, _, _ in PALETTE]:
        if k in seen:
            raise SystemExit(f"duplicate key {k}")
        seen.add(k)


def outputs():
    return {
        "src/AvaEnyo.Theme/Tokens/Palette.axaml": gen_palette(),
        "src/AvaEnyo.Theme/Tokens/BaseResources.axaml": gen_base(),
        "src/AvaEnyo.Theme/Tokens/CompactMetrics.axaml": gen_compact(),
        "tests/AvaEnyo.Theme.Tests/TokenKeys.g.cs": gen_tests(),
    }


def main(argv):
    validate()
    check = "--check" in argv
    stale = []
    for rel, text in outputs().items():
        path = os.path.join(ROOT, rel)
        current = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                current = f.read()
        if current == text:
            continue
        if check:
            stale.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print(f"wrote {rel}")
    if check:
        if stale:
            for rel in stale:
                print(f"stale: {rel}", file=sys.stderr)
            print("Run python3 tools/gen-tokens.py and commit the result.", file=sys.stderr)
            return 1
        print("tokens up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
